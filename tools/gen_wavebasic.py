#!/usr/bin/env python3
# MOD (XT): generates Core/Src/Soundengine/DSPAudio/WaveBasic.c, the
# basic set of the wavetable engine: sine > triangle > square > saw with 7
# in-between frames per pair, in the frame format of wtBuild.h (the same math:
# harmonic levels and phases interpolated, all levels band limited).
# Usage: python3 tools/gen_wavebasic.py
import math, os
H, INTER = 127, 7
LEVELS = [(256, 127), (128, 63), (64, 31), (64, 15), (64, 7), (64, 3)]	# points, harmonics

def spectrum(kind):
    mag, ph = [0.0] * H, [0.0] * H
    for k in range(H):
        h = k + 1
        if kind == 'sine':
            m, p = (1.0, 0.0) if h == 1 else (0.0, 0.0)
        elif kind == 'tri':	# odd harmonics 1/h^2, alternating sign
            m, p = (1.0 / h ** 2, 0.0 if (h // 2) % 2 == 0 else math.pi) if h % 2 else (0.0, 0.0)
        elif kind == 'square':	# odd harmonics 1/h
            m, p = (1.0 / h, 0.0) if h % 2 else (0.0, 0.0)
        else:	# saw: all harmonics 1/h
            m, p = 1.0 / h, 0.0
        mag[k], ph[k] = m, p
    return mag, ph

def wrap(p):
    while p > math.pi: p -= 2 * math.pi
    while p <= -math.pi: p += 2 * math.pi
    return p

def mix(a, b, t):
    mag = [a[0][k] + (b[0][k] - a[0][k]) * t for k in range(H)]
    ph = []
    for k in range(H):
        pa, pb = a[1][k], b[1][k]
        if a[0][k] < 1e-6: pa = pb
        if b[0][k] < 1e-6: pb = pa
        ph.append(wrap(pa + wrap(pb - pa) * t))
    return mag, ph

def level(s, n, hmax):
    y = [0.0] * n
    for k in range(hmax):
        m = s[0][k]
        if m < 1e-6: continue
        for i in range(n):
            y[i] += m * math.sin(2 * math.pi * (k + 1) * i / n + s[1][k])
    return y

def render(s):
    full = level(s, 256, 127)
    g = 30000.0 / max(abs(v) for v in full)
    out = []
    for n, hm in LEVELS:
        y = full if n == 256 else level(s, n, hm)
        out += [max(-32767, min(32767, int(round(v * g)))) for v in y]
    return out

src = [spectrum(k) for k in ('sine', 'tri', 'square', 'saw')]
frames = [render(src[0])]
for i in range(1, len(src)):
    for j in range(1, INTER + 1):
        frames.append(render(mix(src[i - 1], src[i], j / (INTER + 1))))
    frames.append(render(src[i]))

path = os.path.join(os.path.dirname(__file__), '..', 'Core', 'Src', 'Soundengine', 'DSPAudio', 'WaveBasic.c')
with open(path, 'w') as f:
    f.write('/*\n * WaveBasic.c\n *\n * MOD (XT): the basic set of the wavetable engine (WaveVoice.h):\n'
            ' * sine > triangle > square > saw, 7 in-between frames per pair, frame format of\n'
            ' * wtBuild.h. Generated by tools/gen_wavebasic.py, do not edit.\n *\n'
            ' * SPDX-License-Identifier: GPL-3.0-only\n */\n#include <stdint.h>\n#include "SampleRom/wtBuild.h"\n\n')
    f.write('const uint8_t waveBasicFrames = %d;\n' % len(frames))
    f.write('const int16_t waveBasic[%d][WT_FRAME_SIZE] =\n{\n' % len(frames))
    for fr in frames:
        f.write('\t{\n')
        for i in range(0, len(fr), 16):
            f.write('\t\t' + ', '.join(str(v) for v in fr[i:i + 16]) + ',\n')
        f.write('\t},\n')
    f.write('};\n')
print(len(frames), 'frames written to', os.path.normpath(path))
